"""paper/numbers.{md,json,csv}: the ledger of every number the paper may cite, resolved from the result files. Rerunnable; deterministic.
  python scripts/paper/build_ledger.py"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import PAPER, ROOT, resolve  # noqa: E402
from ledger_spec import QUOTES, ROWS  # noqa: E402


def fmt(v, unit):
    if v is None:
        return "-"
    if unit == "auc":
        return f"{v:.3f}"
    if unit == "frac":
        return f"{100 * v:.1f}%"
    if unit == "diff":
        return f"{100 * v:+.1f} pp"
    if unit == "pp":
        return f"{v:.2f} pp"
    if unit == "p":
        return f"{v:.4g}"
    if unit == "count":
        return f"{int(v)}"
    if unit == "steps":
        return f"{v:.1f}"
    return f"{v}"


def resolve_row(r):
    """(value, ci or None, n or None). Derived rows: mean3_range = mean over seeds 0-2 with (min, max) as the interval."""
    if r["derive"] == "mean3_range":
        vals = [resolve(r["file"].format(s=s), r["path"]) for s in (0, 1, 2)]
        return sum(vals) / 3, [min(vals), max(vals)], _n(r)
    v = resolve(r["file"], r["path"])
    ci = None
    if r["ci"] is not None:
        ci = resolve(r["file"], r["ci"])
    return v, ci, _n(r)


def _n(r):
    n = r["n"]
    if n is None:
        return None
    if isinstance(n, int):
        return n
    f = r["file"].format(s=0) if r["derive"] else r["file"]
    return resolve(f, tuple(n))


def display(r, v, ci):
    f = lambda x: fmt(x, r["unit"])  # noqa: E731
    out = f(v)
    if ci is not None:
        out += f" [{100 * ci[0]:+.1f}, {100 * ci[1]:+.1f}]" if r["unit"] == "diff" else f" [{f(ci[0])}, {f(ci[1])}]"
    return out


def main() -> None:
    PAPER.mkdir(exist_ok=True)
    rows = []
    skipped = []
    for r in ROWS:
        if r["file"].endswith("perm_posthoc.json") and not (ROOT / r["file"]).exists():
            skipped.append(r["id"]); continue
        v, ci, n = resolve_row(r)
        src = r["file"] + " :: " + ".".join(str(t) for t in r["path"]) + (f"  (CI: {'.'.join(str(t) for t in r['ci'])})" if r["ci"] else "")
        if r["derive"]:
            src += f"  [{r['derive']} over seeds 0-2]"
        rows.append(dict(id=r["id"], name=r["name"], value=v, ci=ci, n=n, unit=r["unit"], display=display(r, v, ci), source=src, file=r["file"], path=list(r["path"]),
                         ci_path=list(r["ci"]) if r["ci"] else None, part=r["part"], status=r["status"], note=r["note"], derive=r["derive"]))
    ids = {x["id"]: x for x in rows}
    assert len(ids) == len(rows), "duplicate ledger ids"
    mism = []
    for quote, rid, qv, dec, scale, note in QUOTES:
        got = ids[rid]["value"] * scale
        ok = round(got, dec) == round(qv, dec)
        mism.append(dict(quote=quote, id=rid, quoted=qv, source=round(got, max(dec, 3)), match=bool(ok), note=note))
    (PAPER / "numbers.json").write_text(json.dumps({"rows": rows, "quotes": mism}, indent=1, sort_keys=True))
    with open(PAPER / "numbers.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "name", "value", "ci_lo", "ci_hi", "n", "part", "status", "source"])
        for x in rows:
            w.writerow([x["id"], x["name"], repr(x["value"]), "" if x["ci"] is None else repr(x["ci"][0]), "" if x["ci"] is None else repr(x["ci"][1]), "" if x["n"] is None else x["n"], x["part"], x["status"], x["source"]])
    L = ["# Ledger of numbers the paper may cite", "",
         "Generated by `scripts/paper/build_ledger.py` from the result files named in the `source` column (nothing typed by hand); `tests/paper/test_ledger.py` re-resolves every row. "
         "Value / CI are shown rounded; `paper/numbers.json` and `paper/numbers.csv` hold the exact values. Status: **pre-registered** (a rule or hypothesis fixed in a committed plan before the data), "
         "**descriptive** (reported, not tested), **post hoc** (decided after seeing results). Percent columns are fractions x 100; `pp` = percentage points.", "",
         "| id | name | value [95% CI] | n | part | status | source (file :: key path) |", "|---|---|---|---|---|---|---|"]
    for x in rows:
        L.append(f"| `{x['id']}` | {x['name']} | {x['display']} | {'' if x['n'] is None else x['n']} | {x['part']} | {x['status']} | `{x['source']}` |" + (f" {x['note']}" if False else ""))
    L += ["", "## Mismatches", "", "Numbers quoted in chat or in earlier summaries, checked against the sources. `match` means the source rounds to the quoted figure at the quoted precision.", "",
          "| quote | ledger row | quoted | source value | match | what the source covers |", "|---|---|---|---|---|---|"]
    for q in mism:
        L.append(f"| {q['quote']} | `{q['id']}` | {q['quoted']} | {q['source']} | {'yes' if q['match'] else '**NO**'} | {q['note']} |")
    bad = [q for q in mism if not q["match"]]
    g = lambda k: 100 * ids[k]["value"]  # noqa: E731
    L += ["", f"{len(bad)} of {len(mism)} quoted numbers do not round to the source." if bad else "All quoted numbers round to their source. Two are population-dependent and must be cited with their population: "
          f"the gate AUROC ({ids['p2.gate.auroc_seen']['value']:.3f} in the loop on seen tasks, {ids['p2.gate.auroc_all']['value']:.3f} on all tasks, {ids['p1.test_auroc.mean3']['value']:.3f} offline in Part 1) and silent failures "
          f"({g('p2.seen.P0.SF'):.1f}% -> {g('p2.seen.P3.SF'):.1f}% on Part 2 seen tasks; {g('p3.all.P0.SF'):.1f}% -> {g('p3.all.P3.SF'):.1f}% on Part 3 TEST; P0 is {g('p4.P0.SF'):.1f}% on Part 4 TEST)."]
    (PAPER / "numbers.md").write_text("\n".join(L) + "\n")
    if skipped:
        print("SKIPPED (source not yet written):", skipped)
    print(f"{len(rows)} rows, {len(bad)} mismatching quotes")


if __name__ == "__main__":
    main()
